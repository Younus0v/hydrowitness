"""Reference implementation of the Witness Node's signal processing and classifier.

This file is the single written definition of what the node computes. The firmware's portable core
(firmware/witness_node/hw_*.h) must produce the same numbers; tests/test_firmware_core.py checks that
by running both on the same signals.

Pipeline (project document section 4.3)
  block      0.512 s of samples: accelerometer 512 @ 1 kHz (3 axes), microphone 8192 @ 16 kHz
  window     the last two blocks, so a new feature vector every 0.512 s from about one second of data
  features   15 numbers per channel (see FEATURES), mostly in dB
  classifier per-site, two-class diagonal-Gaussian model learned during install calibration
             (hold the button with the pump off, then on). It is linear in the features, i.e. the same
             form as logistic regression, with weights learned on site instead of shipped from a lab.

Nothing here is evidence that the node works on a real pump. It defines the computation. Whether the
features separate ON from OFF on real equipment is measured in validation V3.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

import numpy as np

NFEAT = 15
ACC_FS, ACC_N, ACC_NB, ACC_LO, ACC_HI = 1000, 512, 8, 20.0, 250.0     # MPU6050 accel low-pass is ~260 Hz
MIC_FS, MIC_N, MIC_NB, MIC_LO, MIC_HI = 16000, 8192, 10, 60.0, 8000.0
EPS = 1e-18
MAINS_HALF_WIDTH_HZ = 2.0

DB_FLOOR, FLUX_FLOOR, CREST_FLOOR = 0.25, 1e-4, 1e-2        # variance floors for the classifier
FIT_FRACTION = 0.6                                           # first 60% of each class fits, last 40% tests
GOOD_ACCURACY, FAIR_ACCURACY = 0.97, 0.90
Z_THRESHOLD = 0.35                                           # |z| above this is a confident channel opinion

FEATURES = {
    "acc": ["rms_x_db", "rms_y_db", "rms_z_db"] + [f"band{b}_db" for b in range(ACC_NB)]
           + ["mains1_db", "mains2_db", "flux", "crest"],
    "mic": ["rms_db"] + [f"band{b}_db" for b in range(MIC_NB)] + ["mains1_db", "mains2_db", "flux", "crest"],
}


# ------------------------------------------------------------------------------ tables
def band_bins(fs: int, n: int, lo: float, hi: float, nb: int) -> list[int]:
    edges = lo * (hi / lo) ** (np.arange(nb + 1) / nb)
    return [int(round(float(e) * n / fs)) for e in edges]


def mains_bins(mains_hz: int, mult: int, fs: int, n: int) -> tuple[int, int]:
    centre = int(round(mains_hz * mult * n / fs))
    half = int(round(MAINS_HALF_WIDTH_HZ * n / fs))
    return centre - half, centre + half                      # inclusive range of bins


ACC_KB = band_bins(ACC_FS, ACC_N, ACC_LO, ACC_HI, ACC_NB)
MIC_KB = band_bins(MIC_FS, MIC_N, MIC_LO, MIC_HI, MIC_NB)


def c_header() -> str:
    """The text of firmware/witness_node/hw_tables.h (generated, so nothing is rounded differently in C++)."""
    def arr(name, vals):
        return f"static const int {name}[{len(vals)}] = {{{', '.join(str(v) for v in vals)}}};"
    lines = ["// GENERATED by training/node_reference.py (c_header). Do not edit by hand.",
             "#pragma once", "namespace hw {",
             arr("ACC_KB", ACC_KB), arr("MIC_KB", MIC_KB)]
    for mains in (50, 60):
        for ch, fs, n in (("ACC", ACC_FS, ACC_N), ("MIC", MIC_FS, MIC_N)):
            r = [v for mult in (1, 2) for v in mains_bins(mains, mult, fs, n)]
            lines.append(arr(f"{ch}_MAINS{mains}", r) + "   // 1x low, 1x high, 2x low, 2x high (inclusive bins)")
    lines.append("}  // namespace hw")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------ blocks
@dataclass
class Block:
    var: np.ndarray            # per-axis (acc, 3) or total (mic, 1) variance after mean removal
    band: np.ndarray           # band powers
    m1: float                  # power within +-2 Hz of 1x mains
    m2: float                  # ... of 2x mains
    spec: np.ndarray           # band powers normalized to sum 1, for spectral flux
    crest: float
    flux: float


def hann(n: int) -> np.ndarray:
    return 0.5 - 0.5 * np.cos(2.0 * np.pi * np.arange(n) / (n - 1))


def _power(x: np.ndarray, n: int) -> np.ndarray:
    """One-sided power per bin, scaled so that summing the bins gives about the signal's variance."""
    w = hann(n)
    X = np.fft.rfft((x - x.mean()) * w)
    return 2.0 * (X.real ** 2 + X.imag ** 2) / (n * np.sum(w * w))


def _finish(P: np.ndarray, kb: list[int], mains_hz: int, fs: int, n: int, var: np.ndarray, mag: np.ndarray,
            prev: Optional[Block]) -> Block:
    band = np.array([P[kb[i]:kb[i + 1]].sum() for i in range(len(kb) - 1)])
    (a0, a1), (b0, b1) = mains_bins(mains_hz, 1, fs, n), mains_bins(mains_hz, 2, fs, n)
    tot = band.sum()
    spec = band / tot if tot > 0 else np.zeros_like(band)
    rms = float(np.sqrt(np.mean(mag * mag)))
    crest = float(mag.max() / rms) if rms > 0 else 1.0
    flux = 0.0 if prev is None else float(np.abs(spec - prev.spec).sum())
    return Block(var=var, band=band, m1=float(P[a0:a1 + 1].sum()), m2=float(P[b0:b1 + 1].sum()),
                 spec=spec, crest=crest, flux=flux)


def acc_block(ax: np.ndarray, ay: np.ndarray, az: np.ndarray, mains_hz: int, prev: Optional[Block]) -> Block:
    axes = [np.asarray(a, dtype=np.float64) for a in (ax, ay, az)]
    P = sum(_power(a, ACC_N) for a in axes)
    cent = [a - a.mean() for a in axes]
    var = np.array([float(np.mean(c * c)) for c in cent])
    mag = np.sqrt(sum(c * c for c in cent))
    return _finish(P, ACC_KB, mains_hz, ACC_FS, ACC_N, var, mag, prev)


def mic_block(x: np.ndarray, mains_hz: int, prev: Optional[Block]) -> Block:
    x = np.asarray(x, dtype=np.float64)
    c = x - x.mean()
    return _finish(_power(x, MIC_N), MIC_KB, mains_hz, MIC_FS, MIC_N, np.array([float(np.mean(c * c))]), np.abs(c), prev)


def _db(v: float) -> float:
    return 10.0 * np.log10(v + EPS)


def window_features(kind: str, b0: Block, b1: Block) -> np.ndarray:
    """Features of the window made of two consecutive blocks."""
    out = []
    if kind == "acc":
        out += [_db((b0.var[i] + b1.var[i]) / 2) for i in range(3)]
    else:
        out += [_db((b0.var[0] + b1.var[0]) / 2)]
    out += [_db((b0.band[i] + b1.band[i]) / 2) for i in range(len(b0.band))]
    out += [_db((b0.m1 + b1.m1) / 2), _db((b0.m2 + b1.m2) / 2), (b0.flux + b1.flux) / 2, (b0.crest + b1.crest) / 2]
    assert len(out) == NFEAT
    return np.array(out)


# ------------------------------------------------------------------------- classifier
def variance_floor() -> np.ndarray:
    f = np.full(NFEAT, DB_FLOOR)
    f[13], f[14] = FLUX_FLOOR, CREST_FLOOR
    return f


@dataclass
class Model:
    mu_r: np.ndarray
    mu_s: np.ndarray
    var: np.ndarray
    w: np.ndarray
    m: np.ndarray
    d2: float

    def z(self, x: np.ndarray) -> float:
        """About +1 at a typical RUNNING window, about -1 at a typical STOPPED window."""
        if self.d2 <= 1e-6:
            return 0.0
        return float(np.dot(self.w, np.asarray(x) - self.m) / (self.d2 / 2.0))


def fit(R: np.ndarray, S: np.ndarray) -> Model:
    R, S = np.asarray(R, dtype=np.float64), np.asarray(S, dtype=np.float64)
    mu_r, mu_s = R.mean(axis=0), S.mean(axis=0)
    var = (R.var(axis=0) + S.var(axis=0)) / 2.0 + variance_floor()
    w = (mu_r - mu_s) / var
    d2 = float(np.sum((mu_r - mu_s) ** 2 / var))
    return Model(mu_r, mu_s, var, w, (mu_r + mu_s) / 2.0, d2)


@dataclass
class Calibration:
    model: Model
    acc_r: float               # held-out accuracy on RUNNING windows
    acc_s: float               # ... on STOPPED windows
    quality: float             # min of the two
    verdict: str               # GOOD | FAIR | POOR


def calibrate(R: np.ndarray, S: np.ndarray) -> Calibration:
    """Fit on the first 60% of each class, test on the last 40%, then refit on everything."""
    R, S = np.asarray(R), np.asarray(S)
    nr, ns = max(2, int(len(R) * FIT_FRACTION)), max(2, int(len(S) * FIT_FRACTION))
    trial = fit(R[:nr], S[:ns])
    acc_r = float(np.mean([trial.z(x) > 0 for x in R[nr:]])) if len(R) > nr else 0.0
    acc_s = float(np.mean([trial.z(x) < 0 for x in S[ns:]])) if len(S) > ns else 0.0
    q = min(acc_r, acc_s)
    verdict = "GOOD" if q >= GOOD_ACCURACY else "FAIR" if q >= FAIR_ACCURACY else "POOR"
    return Calibration(fit(R, S), acc_r, acc_s, q, verdict)


def z_to_state(z: float, usable: bool = True) -> str:
    if not usable:
        return "U"
    return "R" if z > Z_THRESHOLD else "S" if z < -Z_THRESHOLD else "U"
